/**
 * Auth seam (OSS requirement §6). release-radar authenticates through an
 * `AuthProvider` interface, not a hardcoded IdP — OAuth is impl #1; an
 * external adopter drops in their own OIDC provider without touching routes.
 * Allowed email domains are config (ALLOWED_EMAIL_DOMAINS), never constants.
 */

/** A verified identity returned by a provider after the OAuth exchange. */
export interface VerifiedProfile {
  /** Stable provider-side user id. */
  providerUserId: string
  /** Email address (lower-cased by the provider impl). */
  email: string
  /** The provider's attestation that it verified the email. The gate FAILS
   *  CLOSED if this is not strictly true — an unverified email is untrusted. */
  emailVerified: boolean
  /** Optional display name. */
  name?: string | null
  /** Optional opaque tokens to persist (encrypted) for later provider calls. */
  tokens?: unknown
}

export interface AuthProvider {
  /** Provider id for logging/telemetry (e.g. "oauth"). */
  readonly id: string
  /**
   * Build the IdP authorize URL to redirect the browser to. `state` and
   * `codeChallenge` are generated by the caller (CSRF + PKCE) and echoed back
   * on the callback.
   */
  buildAuthorizeUrl(params: {
    redirectUri: string
    state: string
    codeChallenge: string
  }): string
  /**
   * Exchange an authorization code (+ PKCE verifier) for a verified profile.
   * Throws on any failure; the caller maps it to a friendly auth-error page.
   */
  exchangeCode(params: {
    code: string
    codeVerifier: string
    redirectUri: string
  }): Promise<VerifiedProfile>
}

/** Reason a login was refused, for logging (never leak specifics to the user). */
export type GateDenial =
  | 'email_missing'
  | 'email_unverified'
  | 'domain_not_allowed'

export interface GateResult {
  allowed: boolean
  reason?: GateDenial
}

/**
 * The fail-closed access gate (§2 auth). A profile is admitted ONLY when:
 *   1. it carries an email,
 *   2. the provider attests the email is verified, AND
 *   3. the email's domain is in the configured allow-list.
 * Any missing/false condition denies. `allowedDomains` must be non-empty
 * (resolveConfig guarantees this) so an empty list can never mean "allow all".
 */
export function checkDomainGate(
  profile: Pick<VerifiedProfile, 'email' | 'emailVerified'>,
  allowedDomains: string[]
): GateResult {
  if (!profile.email) return { allowed: false, reason: 'email_missing' }
  if (!profile.emailVerified) {
    return { allowed: false, reason: 'email_unverified' }
  }
  const at = profile.email.lastIndexOf('@')
  const domain = at >= 0 ? profile.email.slice(at + 1).toLowerCase() : ''
  if (!domain || !allowedDomains.includes(domain)) {
    return { allowed: false, reason: 'domain_not_allowed' }
  }
  return { allowed: true }
}
